#!/usr/bin/env python3
"""Generate indexed 8x8 and 10x10 Cyrillic glyphs from the canonical atlas.

The runtime accepts palette-indexed pixels, not anti-aliased alpha.  This
generator uses box filtering to preserve source coverage, then applies one
coverage threshold to a white pixel (0x05).  This avoids bicubic ringing and
grey fringe pixels that become visual artifacts on the tile renderer.  A shared
source crop keeps every glyph on the same baseline and horizontal grid.
"""

from __future__ import annotations

import argparse
from pathlib import Path

from PIL import Image
from create_cyrillic_font import GLYPHS, read_bmp

SOURCE_CELL = 20
COVERAGE_BRIGHTNESS_THRESHOLD = 8
COVERAGE_THRESHOLD = COVERAGE_BRIGHTNESS_THRESHOLD * 255 // 31
SOURCE_CROP = (4, 7, 16, 20)
TARGET_SIZES = (8, 10)


def brightness(pixel: int) -> int:
    return ((pixel & 0x1F) + ((pixel >> 5) & 0x1F) + ((pixel >> 10) & 0x1F)) // 3


def fit_glyph(pixels: list[int], glyph_index: int, target: int) -> list[int]:
    values = bytes(
        brightness(pixels[(glyph_index * SOURCE_CELL + y) * SOURCE_CELL + x]) * 255 // 31
        for y in range(SOURCE_CELL)
        for x in range(SOURCE_CELL)
    )
    source = Image.frombytes("L", (SOURCE_CELL, SOURCE_CELL), values)
    cropped = source.crop(SOURCE_CROP)
    resized = cropped.resize(
        (target - 2, target - 1),
        Image.Resampling.BOX,
    )

    output = [[False] * target for _ in range(target)]
    for y in range(target - 1):
        for x in range(target - 2):
            output[y][x + 1] = (
                0x05 if resized.getpixel((x, y)) >= COVERAGE_THRESHOLD else 0x00
            )

    return [value for row in output for value in row]


def render(source: Path) -> str:
    width, height, pixels = read_bmp(source)
    expected = (SOURCE_CELL, SOURCE_CELL * len(GLYPHS))
    if (width, height) != expected:
        raise ValueError(f"{source}: expected {expected[0]}x{expected[1]}, got {width}x{height}")

    lines = [
        "// Auto-generated from gfx/cyrillic.bmp.",
        "// DO NOT HAND EDIT.",
        "// Generated by create_cyrillic_indexed_font.py.",
        "",
    ]
    for target in TARGET_SIZES:
        values = []
        for glyph_index in range(len(GLYPHS)):
            values.extend(fit_glyph(pixels, glyph_index, target))
        lines.append(f"const unsigned char cyrillic_{target}_Tiles[{len(GLYPHS)} * {target} * {target}] = {{")
        for start in range(0, len(values), 16):
            chunk = values[start:start + 16]
            suffix = "," if start + 16 < len(values) else ""
            lines.append("    " + ",".join(f"0x{value:02x}" for value in chunk) + suffix)
        lines.extend(["};", ""])
    return "\n".join(lines)


def main() -> int:
    root = Path(__file__).resolve().parent
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=root / "gfx/cyrillic.bmp")
    parser.add_argument("--output", type=Path, default=root / "gfx/cyrillic_8.c")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    generated = render(args.source)
    if args.check:
        if not args.output.exists() or args.output.read_text(encoding="utf-8") != generated:
            raise SystemExit(f"{args.output} is stale; run {Path(__file__).name}")
    else:
        args.output.write_text(generated, encoding="utf-8", newline="\n")
        print(f"Generated {args.output} from {args.source} ({len(GLYPHS)} glyphs)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
