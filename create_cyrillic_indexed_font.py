#!/usr/bin/env python3
"""Generate indexed 8x8 and 10x10 Cyrillic glyphs from the canonical atlas.

The checked-in gfx/cyrillic.bmp is a 20x20-cell bitmap font.  This generator
fits every glyph into the runtime text tiles and preserves a one-pixel safety
margin.  A low coverage threshold keeps anti-aliased source pixels, making the
result slightly heavier without allowing glyphs to touch adjacent cells.
"""

from __future__ import annotations

import argparse
from pathlib import Path

from create_cyrillic_font import GLYPHS, read_bmp

SOURCE_CELL = 20
BRIGHTNESS_THRESHOLD = 4
TARGET_SIZES = (8, 10)


def brightness(pixel: int) -> int:
    return ((pixel & 0x1F) + ((pixel >> 5) & 0x1F) + ((pixel >> 10) & 0x1F)) // 3


def fit_glyph(pixels: list[int], glyph_index: int, target: int) -> list[int]:
    source = [
        [brightness(pixels[(glyph_index * SOURCE_CELL + y) * SOURCE_CELL + x]) >= BRIGHTNESS_THRESHOLD
         for x in range(SOURCE_CELL)]
        for y in range(SOURCE_CELL)
    ]
    points = [(x, y) for y, row in enumerate(source) for x, on in enumerate(row) if on]
    if not points:
        return [0] * (target * target)

    min_x = min(x for x, _ in points)
    max_x = max(x for x, _ in points)
    min_y = min(y for _, y in points)
    max_y = max(y for _, y in points)
    cropped = [row[min_x:max_x + 1] for row in source[min_y:max_y + 1]]

    max_height = target - 2
    max_width = target - 2
    scale = min(max_height / len(cropped), max_width / len(cropped[0]))
    width = max(1, round(len(cropped[0]) * scale))
    height = max(1, round(len(cropped) * scale))
    offset_x = (target - width) // 2
    offset_y = 1

    output = [[False] * target for _ in range(target)]
    for y in range(height):
        source_y = min(len(cropped) - 1, int((y + 0.5) * len(cropped) / height))
        for x in range(width):
            source_x = min(len(cropped[0]) - 1, int((x + 0.5) * len(cropped[0]) / width))
            output[offset_y + y][offset_x + x] = cropped[source_y][source_x]


    return [0x05 if on else 0x00 for row in output for on in row]


def render(source: Path) -> str:
    width, height, pixels = read_bmp(source)
    expected = (SOURCE_CELL, SOURCE_CELL * len(GLYPHS))
    if (width, height) != expected:
        raise ValueError(f"{source}: expected {expected[0]}x{expected[1]}, got {width}x{height}")

    lines = [
        "// Auto-generated from gfx/cyrillic.bmp.",
        "// DO NOT HAND EDIT.",
        "// Generated by create_cyrillic_indexed_font.py.",
        "",
    ]
    for target in TARGET_SIZES:
        values = []
        for glyph_index in range(len(GLYPHS)):
            values.extend(fit_glyph(pixels, glyph_index, target))
        lines.append(f"const unsigned char cyrillic_{target}_Tiles[{len(GLYPHS)} * {target} * {target}] = {{")
        for start in range(0, len(values), 16):
            chunk = values[start:start + 16]
            suffix = "," if start + 16 < len(values) else ""
            lines.append("    " + ",".join(f"0x{value:02x}" for value in chunk) + suffix)
        lines.extend(["};", ""])
    return "\n".join(lines)


def main() -> int:
    root = Path(__file__).resolve().parent
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=root / "gfx/cyrillic.bmp")
    parser.add_argument("--output", type=Path, default=root / "gfx/cyrillic_8.c")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    generated = render(args.source)
    if args.check:
        if not args.output.exists() or args.output.read_text(encoding="utf-8") != generated:
            raise SystemExit(f"{args.output} is stale; run {Path(__file__).name}")
    else:
        args.output.write_text(generated, encoding="utf-8", newline="\n")
        print(f"Generated {args.output} from {args.source} ({len(GLYPHS)} glyphs)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
